package httpapi

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"time"
	"unicode/utf16"
)

type plannerTask struct {
	ID, Text           string
	Completed          bool
	Category, Priority string
}

func decodePlannerState(raw json.RawMessage) (map[string][]plannerTask, bool) {
	if len(raw) > 2*1024*1024 {
		return nil, false
	}
	m, err := fields(raw, "version", "months")
	if err != nil || string(m["version"]) != "1" {
		return nil, false
	}
	var months map[string]json.RawMessage
	if json.Unmarshal(m["months"], &months) != nil || len(months) > 120 {
		return nil, false
	}
	result := make(map[string][]plannerTask, len(months))
	for key, rawTasks := range months {
		if _, err := time.Parse("2006-01", key); err != nil {
			return nil, false
		}
		if len(key) != 7 || key[4] != '-' || key[:4] < "1970" || key[:4] > "9999" || key[5:] < "01" || key[5:] > "12" {
			return nil, false
		}
		var items []json.RawMessage
		if json.Unmarshal(rawTasks, &items) != nil || len(items) > 300 {
			return nil, false
		}
		ids := map[string]bool{}
		for _, rawTask := range items {
			var t map[string]json.RawMessage
			err := json.Unmarshal(rawTask, &t)
			for key := range t {
				if key != "id" && key != "text" && key != "completed" && key != "category" && key != "priority" {
					return nil, false
				}
			}
			if err != nil || !boolean(t["completed"]) {
				return nil, false
			}
			id, validID := text(t["id"])
			content, validText := plannerText(t["text"])
			if !validID || len(id) > 120 || id == "" || ids[id] || !validText || strings.TrimSpace(content) == "" {
				return nil, false
			}
			for _, char := range id {
				if !((char >= 'a' && char <= 'z') || (char >= 'A' && char <= 'Z') || (char >= '0' && char <= '9') || char == '_' || char == '-') {
					return nil, false
				}
			}
			ids[id] = true
			var category, priority string
			if raw, exists := t["category"]; exists {
				if json.Unmarshal(raw, &category) != nil || (category != "work" && category != "learning" && category != "life" && category != "other") {
					return nil, false
				}
			}
			if raw, exists := t["priority"]; exists {
				if json.Unmarshal(raw, &priority) != nil || (priority != "normal" && priority != "high") {
					return nil, false
				}
			}
			result[key] = append(result[key], plannerTask{ID: id, Text: strings.TrimSpace(content), Completed: string(t["completed"]) == "true", Category: category, Priority: priority})
		}
	}
	return result, true
}

func plannerText(raw json.RawMessage) (string, bool) {
	var value string
	if json.Unmarshal(raw, &value) != nil || len(utf16.Encode([]rune(value))) > 500 {
		return "", false
	}
	return value, true
}

func plannerMarkdown(raw json.RawMessage) (string, bool) {
	months, ok := decodePlannerState(raw)
	if !ok {
		return "", false
	}
	keys := make([]string, 0, len(months))
	for key := range months {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var out bytes.Buffer
	out.WriteString("# Monthly Planner\n\n<!-- Generated by D-blog Monthly Planner. Edit task lines or add YYYY-MM sections. -->\n")
	for _, key := range keys {
		fmt.Fprintf(&out, "\n## %s\n\n", key)
		for _, task := range months[key] {
			mark := " "
			if task.Completed {
				mark = "x"
			}
			clean := strings.ReplaceAll(strings.ReplaceAll(task.Text, "\r", " "), "\n", " ")
			clean = strings.ReplaceAll(clean, "<!--", "&lt;!--")
			meta := ""
			if task.Category != "" {
				meta += " category:" + task.Category
			}
			if task.Priority != "" {
				meta += " priority:" + task.Priority
			}
			fmt.Fprintf(&out, "- [%s] %s <!-- id:%s%s -->\n", mark, clean, task.ID, meta)
		}
	}
	return out.String(), true
}
