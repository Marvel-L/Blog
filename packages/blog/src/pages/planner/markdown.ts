import { emptyPlannerState, monthKey, parsePlannerState, type MonthlyPlannerState, type MonthlyTask } from './model';

const HEADER = '# Monthly Planner';
const SECTION = /^##\s+(\d{4})-(0[1-9]|1[0-2])\s*$/;
const TASK = /^-\s+\[([ xX])\]\s+(.+?)(?:\s+<!--\s*id:([A-Za-z0-9_-]{1,120})\s*-->)?\s*$/;
const hash = (input: string) => {
  let value = 2166136261;
  for (const character of input) {
    value ^= character.charCodeAt(0);
    value = Math.imul(value, 16777619);
  }
  return (value >>> 0).toString(36);
};
const makeId = (key: string, text: string, index: number) => `md-${hash(`${key}\u0000${text}\u0000${index}`)}`;

export const parsePlannerMarkdown = (markdown: string): MonthlyPlannerState => {
  if (markdown.length > 2 * 1024 * 1024) throw new Error('Markdown 文件不能超过 2MB');
  const state = emptyPlannerState();
  let current = '';
  const used = new Set<string>();
  for (const raw of markdown.replace(/^\uFEFF/, '').split(/\r?\n/)) {
    const line = raw.trimEnd();
    const section = line.match(SECTION);
    if (section) {
      current = monthKey(Number(section[1]), Number(section[2]));
      state.months[current] ??= [];
      continue;
    }
    if (!line.trim() || line.trimStart().startsWith('#') || line.trimStart().startsWith('<!--')) continue;
    const task = line.match(TASK);
    if (!task || !current) throw new Error(`无法识别的 Markdown 行：${line.slice(0, 80)}`);
    const text = task[2].trim();
    if (!text || text.length > 500) throw new Error('任务文本不能为空且不能超过 500 字');
    const candidate = task[3] || makeId(current, text, state.months[current].length);
    let id = candidate;
    let suffix = 2;
    while (used.has(id)) id = `${candidate}-${suffix++}`;
    used.add(id);
    state.months[current].push({ id, text, completed: task[1].toLowerCase() === 'x' });
    if (state.months[current].length > 300) throw new Error('每月最多支持 300 个任务');
  }
  return parsePlannerState(JSON.stringify(state));
};

const safeText = (text: string) => text.replace(/\r?\n/g, ' ').replace(/<!--/g, '&lt;!--').trim();

export const plannerToMarkdown = (state: MonthlyPlannerState): string => {
  const parsed = parsePlannerState(JSON.stringify(state));
  const lines = [
    HEADER,
    '',
    '<!-- Generated by D-blog Monthly Planner. Edit task lines or add YYYY-MM sections. -->',
    '',
  ];
  const keys = Object.keys(parsed.months).sort();
  if (keys.length === 0) return `${lines.join('\n')}\n`;
  for (const key of keys) {
    lines.push(`## ${key}`, '');
    for (const task of parsed.months[key]) {
      lines.push(`- [${task.completed ? 'x' : ' '}] ${safeText(task.text)} <!-- id:${task.id} -->`);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
};

export const tasksFor = (state: MonthlyPlannerState, year: number, month: number): MonthlyTask[] =>
  state.months[monthKey(year, month)] ?? [];
